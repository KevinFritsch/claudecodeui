#!/usr/bin/env node
/**
 * Builds src/modules/work/slackEmoji.data.ts (the reaction picker's emoji set)
 * from iamcal's emoji-datasource, which is the set and the names Slack uses.
 *
 *   curl -sfLo /tmp/emoji.json https://cdn.jsdelivr.net/npm/emoji-datasource@15.1.2/emoji.json
 *   node scripts/generate-slack-emoji.mjs /tmp/emoji.json
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const source = process.argv[2];
if (!source) throw new Error('usage: generate-slack-emoji.mjs <emoji.json>');
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const CATEGORIES = ['Smileys & Emotion', 'People & Body', 'Animals & Nature', 'Food & Drink', 'Activities', 'Travel & Places', 'Objects', 'Symbols', 'Flags'];

const toChar = (unified) => String.fromCodePoint(...unified.split('-').map((h) => parseInt(h, 16)));
const rows = JSON.parse(readFileSync(source, 'utf8'))
  .filter((e) => CATEGORIES.includes(e.category))
  .sort((a, b) => CATEGORIES.indexOf(a.category) - CATEGORIES.indexOf(b.category) || a.sort_order - b.sort_order)
  .map((e) => [toChar(e.unified), e.short_name, e.short_names.filter((n) => n !== e.short_name).join(' '), CATEGORIES.indexOf(e.category)]);

const out = `/**
 * Slack's emoji set (iamcal emoji-datasource 15.1.2, MIT): [emoji, Slack name,
 * other names, category index]. Generated by scripts/generate-slack-emoji.mjs.
 */
export const SLACK_EMOJI_CATEGORIES = ${JSON.stringify(CATEGORIES)};

// prettier-ignore
export const SLACK_EMOJI: Array<[string, string, string, number]> = ${JSON.stringify(rows)};
`;
writeFileSync(join(root, 'src/modules/work/slackEmoji.data.ts'), out);
console.log(`${rows.length} emoji`);
